def transparent_sprite(image):
    rgba = image.convert('RGBA')
    alpha = rgba.getchannel('A').point(lambda value: 255 if value > 24 else 0)
    rgba.putalpha(alpha)
    bounds = alpha.getbbox()
    if not bounds:
        raise RuntimeError('Found an empty sprite cell')
    return rgba.crop(bounds)


def build(class_id, spec):
    source = Image.open(ROOT / spec['source']).convert('RGBA')
    if source.width < 4 or source.height < 4:
        raise RuntimeError(f'Invalid source image for {class_id}: {source.size}')
    atlas = Image.new('RGBA', (FRAME * 4, FRAME * 4), (0, 0, 0, 0))
    metadata = {}
    for index, item_id in enumerate(spec['items']):
        column, row = index % 4, index // 4
        x0, x1 = round(column * source.width / 4), round((column + 1) * source.width / 4)
        y0, y1 = round(row * source.height / 4), round((row + 1) * source.height / 4)
        override = spec.get('overrides', {}).get(index)
        cell = Image.open(ROOT / override).convert('RGBA') if override else source.crop((x0, y0, x1, y1))
        sprite = transparent_sprite(cell)
        max_size = FRAME - PADDING * 2
        scale = min(max_size / sprite.width, max_size / sprite.height)
        width, height = max(1, round(sprite.width * scale)), max(1, round(sprite.height * scale))
        sprite = sprite.resize((width, height), Image.Resampling.NEAREST)
        px, py = (FRAME - width) // 2, (FRAME - height) // 2
        frame_x, frame_y = column * FRAME, row * FRAME
        atlas.alpha_composite(sprite, (frame_x + px, frame_y + py))
        metadata[item_id] = {
            'frame': index,
            'atlas': f'items-{class_id}',
            'content': {'x': px, 'y': py, 'width': width, 'height': height},
        }
    destination = ROOT / spec['destination']
    destination.parent.mkdir(parents=True, exist_ok=True)
    atlas.save(destination, optimize=True)
    return metadata


